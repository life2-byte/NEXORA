def _render(name: str, color: str, size: int) -> QPixmap:
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" '
        f'stroke="{color}" stroke-width="1.8" stroke-linecap="round" '
        f'stroke-linejoin="round">{_PATHS[name]}</svg>'
    )
    renderer = QSvgRenderer(QByteArray(svg.encode("utf-8")))
    pixmap = QPixmap(size, size)
    pixmap.fill(Qt.GlobalColor.transparent)
    painter = QPainter(pixmap)
    renderer.render(painter)
    painter.end()
    return pixmap


def get_icon(
    name: str,
    color: str,
    active_color: str | None = None,
    hover_color: str | None = None,
    size: int = 64,
) -> QIcon:
    """color = normal, active_color = checked state, hover_color = mouse upar aaye
    (hover ke liye button pe setAutoRaise(True) zaroori hai)."""
    icon = QIcon()
    normal = _render(name, color, size)
    checked = _render(name, active_color, size) if active_color else normal
    icon.addPixmap(normal, QIcon.Mode.Normal, QIcon.State.Off)
    icon.addPixmap(checked, QIcon.Mode.Normal, QIcon.State.On)
    if hover_color:
        hover = _render(name, hover_color, size)
        icon.addPixmap(hover, QIcon.Mode.Active, QIcon.State.Off)
        icon.addPixmap(checked if active_color else hover, QIcon.Mode.Active, QIcon.State.On)
    return icon